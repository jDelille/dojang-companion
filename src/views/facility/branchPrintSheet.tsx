import type { Branch } from "../../types/branches";
import {
  BRANCH_TODAY,
  MANAGERS,
  capPct,
  fmtDate,
  hoursOf,
  mgrName,
} from "../../utils/json/branchesData";
import { moneyWhole } from "../../utils/formatUtils";

/*
   Print sheet — ported from the hidden #print-sheet div and printBranches() /
   printHead() in tailwind/src/assets/js/branches.js. A single id renders the
   key/value detail table; multiple ids render the branch register table. The
   page fills this then calls window.print().
*/

const num = (n: number) => n.toLocaleString("en-US");

const PrintHead = ({ title, sub }: { title: string; sub: string }) => (
  <div className="ps-head">
    <div>
      <div className="ps-brand">Dreams GYM</div>
      <div className="ps-sub">Branch Management</div>
    </div>
    <div className="ps-meta">
      <div className="ps-title ps-title-inline">{title}</div>
      <div className="ps-sub">{sub}</div>
    </div>
  </div>
);

type BranchPrintSheetProps = {
  branches: Branch[];
};

const BranchPrintSheet = ({ branches }: BranchPrintSheetProps) => {
  if (branches.length === 1) {
    const b = branches[0];
    const m = MANAGERS.find((x) => x.id === b.managerId) ?? null;
    const rows: [string, string][] = [
      ["City", b.city],
      ["Address", b.address],
      ["Status", b.status],
      ["Headquarters", b.hq ? "Yes" : "No"],
      ["Manager", m ? m.name + " (" + m.role + ")" : "Unassigned"],
      ["Phone", b.phone],
      ["Email", m ? m.email : "—"],
      ["Hours", hoursOf(b)],
      ["Members", num(b.members) + " / " + num(b.capacity) + " (" + capPct(b) + "%)"],
      ["Staff", String(b.staff)],
      ["Monthly revenue", moneyWhole(b.revenue)],
      ["Rating", b.rating ? b.rating.toFixed(1) + " / 5.0" : "Not rated yet"],
      ["Amenities", b.amenities.length ? b.amenities.join(", ") : "None"],
      [
        "Opened",
        b.opened ? fmtDate(b.opened) : b.openingDate ? "Opening " + fmtDate(b.openingDate) : "—",
      ],
    ];
    return (
      <div id="print-sheet" className="print-sheet" aria-hidden="true">
        <PrintHead title={b.name} sub={"Printed " + fmtDate(BRANCH_TODAY)} />
        <table className="ps-table ps-table-key">
          <tbody>
            {rows.map((r) => (
              <tr key={r[0]}>
                <th>{r[0]}</th>
                <td>{r[1]}</td>
              </tr>
            ))}
          </tbody>
        </table>
        <div className="ps-foot">
          Generated by Dreams GYM on {fmtDate(BRANCH_TODAY)} · This document is for internal use
          only.
        </div>
      </div>
    );
  }

  const totalMembers = branches.reduce((s, b) => s + b.members, 0);
  return (
    <div id="print-sheet" className="print-sheet" aria-hidden="true">
      {branches.length > 0 && (
        <>
          <PrintHead
            title="Branch Register"
            sub={branches.length + " branches · printed " + fmtDate(BRANCH_TODAY)}
          />
          <table className="ps-table">
            <thead>
              <tr>
                <th>Branch</th>
                <th>City</th>
                <th>Manager</th>
                <th>Members</th>
                <th>Capacity</th>
                <th>Revenue</th>
                <th>Status</th>
              </tr>
            </thead>
            <tbody>
              {branches.map((b) => (
                <tr key={b.id}>
                  <td>{b.name}</td>
                  <td>{b.city}</td>
                  <td>{mgrName(b)}</td>
                  <td>{num(b.members)}</td>
                  <td>{capPct(b)}%</td>
                  <td>{moneyWhole(b.revenue)}</td>
                  <td>{b.status}</td>
                </tr>
              ))}
            </tbody>
          </table>
          <div className="ps-foot">
            Generated by Dreams GYM on {fmtDate(BRANCH_TODAY)} · {branches.length} records · total
            members {num(totalMembers)}.
          </div>
        </>
      )}
    </div>
  );
};

export default BranchPrintSheet;

import type { CalendarEvent } from "../../../types/calendarApp";
import { TODAY, fmtDateLong, fmtDateShort, fmtDur, fmtTime, remindLabel } from "../../../utils/json/calendarAppData";

/*
   Print sheet — ported from the hidden #print-sheet div and printEvents() /
   printHead() in tailwind/src/assets/js/calendar-app.js. A single event
   renders the key/value detail table; multiple events render the schedule
   register table. The page fills this then calls window.print().
*/

const PrintHead = ({ title, sub }: { title: string; sub: string }) => (
  <div className="ps-head">
    <div>
      <div className="ps-brand">Dreams GYM</div>
      <div className="ps-sub">Calendar · Austin HQ</div>
    </div>
    <div className="ps-meta">
      <div className="ps-title ps-title-inline">{title}</div>
      <div className="ps-sub">{sub}</div>
    </div>
  </div>
);

type CalendarPrintSheetProps = {
  events: CalendarEvent[];
  seriesCount: (id: number) => number;
};

const CalendarPrintSheet = ({ events, seriesCount }: CalendarPrintSheetProps) => {
  const list = events
    .slice()
    .sort((a, b) => a.date.localeCompare(b.date) || a.start.localeCompare(b.start) || a.id - b.id);

  if (list.length === 1) {
    const e = list[0];
    const rows: [string, string][] = [
      ["Date", fmtDateLong(e.date)],
      ["Time", fmtTime(e.start) + " – " + fmtTime(e.end || e.start)],
      ["Duration", e.end ? fmtDur(e.start, e.end) : "—"],
      ["Type", e.type],
      ["Location", e.location],
      ["Trainer / owner", e.trainer || "Unassigned"],
      ["Capacity", e.capacity ? e.capacity + " places" : "—"],
      ["Reminder", e.reminder ? remindLabel(e.reminder.minutes) + " · " + e.reminder.channel : "None"],
      ["Repeats", e.seriesId ? "Part of a series of " + seriesCount(e.id) : "Does not repeat"],
      ["Notes", e.notes || "—"],
    ];
    return (
      <div id="print-sheet" className="print-sheet" aria-hidden="true">
        <PrintHead title={e.title} sub={"Printed " + fmtDateShort(TODAY)} />
        <table className="ps-table">
          <tbody>
            {rows.map((r) => (
              <tr key={r[0]}>
                <th>{r[0]}</th>
                <td>{r[1]}</td>
              </tr>
            ))}
          </tbody>
        </table>
        <div className="ps-foot">
          Generated by Dreams GYM on {fmtDateShort(TODAY)} · This document is for internal use only.
        </div>
      </div>
    );
  }

  return (
    <div id="print-sheet" className="print-sheet" aria-hidden="true">
      {list.length > 0 && (
        <>
          <PrintHead title="Schedule" sub={list.length + " events · printed " + fmtDateShort(TODAY)} />
          <table className="ps-table">
            <thead>
              <tr>
                <th>Date</th>
                <th>Time</th>
                <th>Event</th>
                <th>Type</th>
                <th>Location</th>
                <th>Owner</th>
              </tr>
            </thead>
            <tbody>
              {list.map((e) => (
                <tr key={e.id}>
                  <td>{fmtDateShort(e.date)}</td>
                  <td>{fmtTime(e.start) + "–" + fmtTime(e.end || e.start)}</td>
                  <td>{e.title}</td>
                  <td>{e.type}</td>
                  <td>{e.location}</td>
                  <td>{e.trainer || "—"}</td>
                </tr>
              ))}
            </tbody>
          </table>
          <div className="ps-foot">
            Generated by Dreams GYM on {fmtDateShort(TODAY)} · {list.length} records.
          </div>
        </>
      )}
    </div>
  );
};

export default CalendarPrintSheet;
